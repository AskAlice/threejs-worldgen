// Demo cards and the docs map for the READMEs, generated from the lander data in landing/packages/*.mjs, the root
// package.json workspaces and the demo pages in example/.
//
//   node landing/readme-cards.mjs
//
// README.md is also the TypeDoc home page. It gets a docs map (every public package with its API modules, landing page
// and demos, each demo as a three.js and an R3F link) and a grid of cards (thumbnail, name, pitch, links) for every
// package with a live demo. Each packages/<short>/README.md gets a hero image and a "Live demo · Landing page · API
// docs" row under its title. Everything goes between the marker comments below and is replaced on every run, so
// running it twice changes nothing. Images and links are absolute URLs on the published site so they work on GitHub,
// npm and in TypeDoc, and use HTML (<img width>, <table>) because markdown images can't be sized. A package without a
// thumbnail gets a text-only card. `landing/check.mjs` fails the site build when the map misses a package or a demo.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { join } from 'node:path'
import { SITE, ORDER, DEMOS, esc, plain, imgAlt } from './seo.mjs'

export const START = '<!-- demo-cards:start (generated by landing/readme-cards.mjs, do not edit) -->'
export const END = '<!-- demo-cards:end -->'
export const MAP_START = '<!-- docs-map:start (generated by landing/readme-cards.mjs, do not edit) -->'
export const MAP_END = '<!-- docs-map:end -->'
const COLS = 3
const THUMB_WIDTH = 240 // three cards fit GitHub's README column

const demoUrl = (d) => `${SITE}demo/${d.href}`
const landingUrl = (p) => `${SITE}${p.short}/`
const apiUrl = (module) => `${SITE}docs/modules/${module.replace('/', '_')}.html` // TypeDoc: threejs-x/react -> threejs-x_react
const docsUrl = (p) => apiUrl(p.name)
const alt = (p, img) => esc(`${p.name}: ${plain(imgAlt(p, img) ?? p.pitch)}`)
const a = (href, text) => `<a href="${esc(href)}">${text}</a>`

/** "Live demo · <other demos> · Landing page · API docs". */
function linkRow(p, allDemos) {
  const demos = (allDemos ? p.demos : p.demos.slice(0, 1)).map((d, i) => a(demoUrl(d), i ? esc(d.label) : 'Live demo'))
  return [...demos, a(landingUrl(p), 'Landing page'), a(docsUrl(p), 'API docs')].join(' · ')
}

function card(p) {
  const href = p.demos[0] ? demoUrl(p.demos[0]) : landingUrl(p)
  const img = p.thumb ? `${a(href, `<img src="${SITE}media/${p.thumb}" width="${THUMB_WIDTH}" alt="${alt(p, p.thumb)}" />`)}<br />` : ''
  return `<td valign="top" width="${THUMB_WIDTH}">${img}<b>${a(landingUrl(p), esc(p.name))}</b><br />${esc(plain(p.pitch))}<br />${linkRow(p, false)}</td>`
}

/**
 * The root README grid. `pkgs` are lander data with `demos` already filtered to built pages and `thumb` / `heroImg`
 * resolved to existing media paths (or null). Packages without a demo are left out.
 */
export function grid(pkgs) {
  const cards = pkgs.filter((p) => p.demos.length).map(card)
  const rows = []
  for (let i = 0; i < cards.length; i += COLS) rows.push(`<tr>\n${cards.slice(i, i + COLS).join('\n')}\n</tr>`)
  return `<table>\n${rows.join('\n')}\n</table>`
}

/** The block under a package README's title: hero image (if any) and the link row. */
export function packageBlock(p) {
  const href = p.demos[0] ? demoUrl(p.demos[0]) : landingUrl(p)
  const hero = p.heroImg ? `<p>${a(href, `<img src="${SITE}media/${p.heroImg}" alt="${alt(p, p.heroImg)}" />`)}</p>\n` : ''
  return `${hero}<p><b>${linkRow(p, true)}</b></p>`
}

/** Puts `block` between the markers, or right under the first `# ` title when the markers aren't there yet. */
export function replaceBlock(text, block, start = START, end = END) {
  const wrapped = `${start}\n${block}\n${end}`
  const s = text.indexOf(start)
  const e = text.indexOf(end)
  if (s !== -1 && e > s) return text.slice(0, s) + wrapped + text.slice(e + end.length)
  const title = text.match(/^# .*\n/m)
  if (!title) throw new Error('no markers and no "# " title to insert under')
  const at = title.index + title[0].length
  const rest = text.slice(at)
  return `${text.slice(0, at)}\n${wrapped}\n${rest.startsWith('\n') ? '' : '\n'}${rest}`
}

// ---------- docs map ----------

// Demo pages pair up by name: <name>.html is the three.js page and <name>-r3f.html its React Three Fiber twin. The grass
// pages predate that convention, so they are named here.
const DEMO_NAMES = { 'index.html': 'grass', 'r3f.html': 'grass-r3f' }
const demoName = (f) => DEMO_NAMES[f] ?? f.replace(/\.html$/, '')
const pageOf = (href) => href.split(/[?#]/)[0]

/** Pairs demo pages (file names in example/) into `{ name, three, r3f }`, with null for a missing twin. */
export function pairDemos(files) {
  const pairs = new Map()
  for (const f of files) {
    const name = demoName(f).replace(/-r3f$/, '')
    if (!pairs.has(name)) pairs.set(name, { name, three: null, r3f: null })
    pairs.get(name)[demoName(f).endsWith('-r3f') ? 'r3f' : 'three'] = f
  }
  return [...pairs.values()].sort((x, y) => x.name.localeCompare(y.name))
}

/**
 * The package each demo pair belongs to, as a Map pair -> package (or null: "Everything together / tools"): the first
 * of `pkgs` whose lander lists one of its pages, else the one DEMOS in landing/seo.mjs names for it.
 */
export function demoOwners(pkgs, pairs) {
  const owner = (f) => f && (pkgs.find((p) => p.demos.some((d) => pageOf(d.href) === f)) ?? pkgs.find((p) => p.short === DEMOS[f]?.[0]))
  return new Map(pairs.map((d) => [d, owner(d.three) || owner(d.r3f) || null]))
}

const twin = (f, label) => f ? a(`${SITE}demo/${f}`, label) : `${label}: not yet`
const demoLine = (d) => `${esc(d.name)}: ${twin(d.three, 'three.js')} · ${twin(d.r3f, 'R3F')}`
const row = (cells) => `<tr>${cells.map((c) => `<td valign="top">${c}</td>`).join('')}</tr>`

/**
 * The docs map: a row per package (`{ name, short, pitch, react, landing, demos }`, in order) with its API modules,
 * landing page and demo pairs, then an "Everything together / tools" row for the pairs no package owns. Each pair is
 * listed once, under its owner; a package whose lander demos all belong to another package points there.
 */
export function docsMap(pkgs, pairs) {
  const owners = demoOwners(pkgs, pairs)
  const ownerOf = (href) => [...owners].find(([d]) => [d.three, d.r3f].includes(pageOf(href)))?.[1]
  const rank = (p, d) => p.demos.findIndex((x) => [d.three, d.r3f].includes(pageOf(x.href))) >>> 0
  const rows = pkgs.map((p) => {
    const own = pairs.filter((d) => owners.get(d) === p) // lander order, then the package's own name, then A-Z
      .sort((x, y) => rank(p, x) - rank(p, y) || (x.name !== p.short) - (y.name !== p.short) || x.name.localeCompare(y.name))
    const elsewhere = [...new Set(p.demos.map((d) => ownerOf(d.href)))].filter((o) => o && o !== p)
    const docs = [a(apiUrl(p.name), esc(p.name)), p.react && a(apiUrl(`${p.name}/react`), esc(`${p.name}/react`)), p.landing && a(landingUrl(p), 'Landing page')]
    const demos = own.length ? own.map(demoLine).join('<br />') : elsewhere.length ? `See ${elsewhere.map((o) => esc(o.name)).join(', ')}` : 'No demo yet'
    return row([`<b>${esc(p.name)}</b><br />${esc(plain(p.pitch))}`, docs.filter(Boolean).join('<br />'), demos])
  })
  const loose = pairs.filter((d) => !owners.get(d))
  if (loose.length) rows.push(row(['<b>Everything together / tools</b><br />Demos that use several packages at once.', '', loose.map(demoLine).join('<br />')]))
  return `<table>\n<tr><th align="left">Package</th><th align="left">API reference and landing page</th><th align="left">Demos: three.js · R3F</th></tr>\n${rows.join('\n')}\n</table>`
}

/**
 * What the docs map in `html` (a README or the built docs home) leaves out: the URLs of the API modules of `pkgs`
 * (`{ name, react }`, plus `/react` where `react` is set) and of the demo `pages` that no link between the docs-map
 * markers points to. Empty when the map is complete.
 */
export function missingFromMap(html, pkgs, pages) {
  const s = html.indexOf(MAP_START)
  const e = html.indexOf(MAP_END)
  const hrefs = new Set([...(s !== -1 && e > s ? html.slice(s, e) : '').matchAll(/href="([^"?#]*)/g)].map((m) => m[1]))
  const want = [...pkgs.flatMap((p) => p.react ? [apiUrl(p.name), apiUrl(`${p.name}/react`)] : [apiUrl(p.name)]), ...pages.map((f) => `${SITE}demo/${f}`)]
  return want.filter((u) => !hrefs.has(u))
}

/** The public (not `private`) workspace packages, in `workspaces` order: `{ name, short, description, react }`. */
export function workspacePackages(root) {
  const json = (dir) => JSON.parse(readFileSync(join(root, dir, 'package.json'), 'utf8'))
  return json('.').workspaces.map((dir) => ({ dir, pkg: json(dir) })).filter(({ pkg }) => !pkg.private).map(({ dir, pkg }) =>
    ({ name: pkg.name, short: dir.split('/').pop(), description: pkg.description ?? '', react: !!pkg.exports?.['./react'] }))
}

/** The demo pages in example/: every *.html except demos.html, the index of them all. */
export const demoPages = (root) => readdirSync(join(root, 'example')).filter((f) => f.endsWith('.html') && f !== 'demos.html').sort()

// ---------- CLI ----------

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = fileURLToPath(new URL('..', import.meta.url))
  const media = (f) => f && [join(root, 'landing/media', f), join(root, 'media', f)].some(existsSync) ? f : null
  const hasDemo = (href) => existsSync(join(root, 'example', href.split(/[?#]/)[0] || 'index.html'))
  const order = (x, y) => (ORDER.indexOf(x.short) >>> 0) - (ORDER.indexOf(y.short) >>> 0)
  const pkgs = (await Promise.all(readdirSync(join(root, 'landing/packages')).filter((f) => f.endsWith('.mjs'))
    .map(async (f) => (await import(pathToFileURL(join(root, 'landing/packages', f)))).default)))
    .map((p) => ({ ...p, demos: (p.demos ?? []).filter((d) => hasDemo(d.href)),
      thumb: media(p.thumb) ?? media(p.hero?.img), heroImg: media(p.hero?.img) ?? media(p.thumb) }))
    .sort(order)
  // Every public package, lander or not (packages without one use their package.json description as the pitch).
  const mapPkgs = workspacePackages(root).map((w) => {
    const p = pkgs.find((q) => q.name === w.name)
    return { ...w, pitch: p?.pitch ?? w.description.replace(/[^.]$/, '$&.'), landing: !!p, demos: p?.demos ?? [] }
  }).sort(order)

  // `blocks`: replaceBlock arguments after the text, applied in turn.
  const write = (file, ...blocks) => {
    const before = readFileSync(file, 'utf8')
    const after = blocks.reduce((text, args) => replaceBlock(text, ...args), before)
    if (after !== before) writeFileSync(file, after)
    console.log(`${after === before ? 'unchanged' : 'updated  '} ${file.slice(root.length)}`)
  }
  write(join(root, 'README.md'), [docsMap(mapPkgs, pairDemos(demoPages(root))), MAP_START, MAP_END], [grid(pkgs)])
  for (const p of pkgs) {
    const file = join(root, 'packages', p.short, 'README.md')
    if (existsSync(file)) write(file, [packageBlock(p)])
  }
}
